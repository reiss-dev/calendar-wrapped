#!/usr/bin/env node
// Writes _headers (Cloudflare static assets, Workers and Pages) from js/security-headers.js.
// Run after changing the headers: node tools/make-headers.js. A test checks they match.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECURITY_HEADERS } from '../js/security-headers.js';

export function headersFile() {
  const lines = ['# Generated by tools/make-headers.js from js/security-headers.js. Do not edit by hand.', '/*'];
  for (const [k, v] of Object.entries(SECURITY_HEADERS)) lines.push(`  ${k}: ${v}`);
  lines.push('', '# The service worker must always be checked for updates.', '/sw.js', '  Cache-Control: no-cache');
  return `${lines.join('\n')}\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '_headers'), headersFile());
  console.log('Wrote _headers');
}
