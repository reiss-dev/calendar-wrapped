#!/usr/bin/env node
// Writes sw.js: the service worker that keeps a copy of the app on the device after the first
// visit, so it works with no network at all. That is also the easiest way for anyone (or their
// IT team) to check nothing is sent: open the page once, switch off the network, use it.
// Run after changing any app file: node tools/make-sw.js. A test checks sw.js is current.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir) => readdirSync(join(ROOT, dir)).flatMap((f) => { const p = join(dir, f); return statSync(join(ROOT, p)).isDirectory() ? walk(p) : [p]; });

/** Everything the app needs at runtime, as site-relative paths. */
export function precacheList() {
  const files = [
    'index.html', 'styles.css', 'manifest.webmanifest',
    ...walk('js').filter((f) => f.endsWith('.js') && f !== join('js', 'auth-callback.js')),
    ...walk('vendor').filter((f) => f.endsWith('.js')),
    ...walk('fonts').filter((f) => f.endsWith('.woff2')),
    ...walk('icons').filter((f) => f.endsWith('.png')),
    'sample/work.ics', 'sample/personal.ics', ...walk('sample/team').filter((f) => f.endsWith('.ics')),
  ].map((f) => f.split('\\').join('/')).sort();
  return files;
}

export function swSource() {
  const files = precacheList();
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(readFileSync(join(ROOT, f)));
  const version = hash.digest('hex').slice(0, 12);
  const list = files.map((f) => (f === 'index.html' ? './' : f));
  return `// Generated by tools/make-sw.js. Do not edit by hand.
// Keeps a copy of the app on this device so it works offline. Only the app's own files are
// cached; nothing you load into it is ever stored or sent by this worker.
const VERSION = '${version}';
const CACHE = \`cw-\${VERSION}\`;
const FILES = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('cw-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// Network first, so a new deploy is used straight away; the saved copy when there's no network.
// The server's own routes (payments, share links, preview images) are never cached.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || /^\\/(api|c|og)\\//.test(url.pathname)) return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try {
      const res = await fetch(req);
      if (res.ok && res.type === 'basic' && !res.redirected && FILES.some((f) => url.pathname.endsWith(f === './' ? '/' : \`/\${f}\`))) cache.put(req, res.clone());
      return res;
    } catch (err) {
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      if (req.mode === 'navigate') { const home = await cache.match('./'); if (home) return home; }
      throw err;
    }
  })());
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(ROOT, 'sw.js'), swSource());
  console.log(`Wrote sw.js with ${precacheList().length} files`);
}
