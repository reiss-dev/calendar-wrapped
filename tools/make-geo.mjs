#!/usr/bin/env node
// Builds the bundled geo data from open datasets. Not needed at runtime.
//   npm i --no-save world-atlas@2 topojson-client@3 all-the-cities@3 @nwpr/airport-codes@3
//   node tools/make-geo.mjs
// Sources and licences are listed in js/geo/LICENSES.md.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(process.env.GEO_MODULES ? join(process.env.GEO_MODULES, 'x.js') : import.meta.url);
const topo = req('topojson-client');
const land = req('world-atlas/land-110m.json');
const cities = req('all-the-cities');
const { airports } = req('@nwpr/airport-codes');

// ---------------------------------------------------------------- land dots
// Points on an even grid over the sphere, kept where they fall on land.
const geo = topo.feature(land, land.objects.land);
const rings = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const p of polys) rings.push(p);
}
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const onLand = (lon, lat) => rings.some((poly) => inRing(lon, lat, poly[0]) && !poly.slice(1).some((hole) => inRing(lon, lat, hole)));
const STEP = 1.6;
const dots = [];
for (let lat = -58; lat <= 82; lat += STEP) {
  const lonStep = STEP / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
  for (let lon = -180; lon < 180; lon += lonStep) if (onLand(lon, lat)) dots.push(Math.round(lat * 10), Math.round(lon * 10));
}
const b64 = Buffer.from(new Int16Array(dots).buffer).toString('base64');
writeFileSync(join(root, 'js/geo/land-dots.js'), `// ${dots.length / 2} dots on land, ${STEP}° apart. Generated by tools/make-geo.mjs from Natural Earth 1:110m (public domain).\n// Int16 pairs of latitude and longitude ×10, base64.\nexport default '${b64}';\n`);

// ---------------------------------------------------------------- places
const norm = (s) => String(s).replace(/[øØ]/g, 'o').replace(/[æÆ]/g, 'ae').replace(/ß/g, 'ss').replace(/[łŁ]/g, 'l').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();
const round = (x) => Math.round(x * 100) / 100; // ~1 km, plenty for a globe
const byName = new Map(); // normalised name -> [display, lat, lon, pop]
const put = (name, display, lat, lon, pop) => {
  const k = norm(name);
  if (!k || k.length < 3) return;
  const cur = byName.get(k);
  if (!cur || pop > cur[3]) byName.set(k, [display, round(lat), round(lon), pop]);
};
for (const c of cities) {
  if (c.population < 250000 && c.featureCode !== 'PPLC') continue;
  const [lon, lat] = c.loc.coordinates;
  put(c.name, c.name, lat, lon, c.population);
}
const iata = {};
// Names people use in Dutch, Swedish, Norwegian and Danish (and a few English variants).
const ALIASES = {
  Copenhagen: ['Kopenhagen', 'Köpenhamn', 'København', 'Kobenhavn'], Gothenburg: ['Göteborg', 'Goteborg', 'Gotenburg'],
  Brussels: ['Brussel', 'Bryssel', 'Bruxelles'], 'The Hague': ['Den Haag', "'s-Gravenhage", 'Haag'], Cologne: ['Keulen', 'Köln', 'Koln'],
  Munich: ['München', 'Munchen', 'Muenchen'], Vienna: ['Wenen', 'Wien'], Prague: ['Praag', 'Prag', 'Praha'], Rome: ['Rom', 'Roma'],
  Lisbon: ['Lissabon', 'Lisboa'], Paris: ['Parijs'], London: ['Londen'], Antwerp: ['Antwerpen'], Geneva: ['Genève', 'Geneve', 'Genf', 'Genève'],
  Zurich: ['Zürich'], Warsaw: ['Warschau', 'Warszawa'], Athens: ['Athene', 'Aten', 'Athen'], Milan: ['Milaan', 'Milano'],
  Naples: ['Napels', 'Neapel', 'Napoli'], Venice: ['Venetië', 'Venedig', 'Venezia'], Florence: ['Florens', 'Firenze'],
  Moscow: ['Moskou', 'Moskva'], Beijing: ['Peking'], 'Cape Town': ['Kaapstad', 'Kapstaden', 'Kapstadt'], Edinburgh: ['Edinburg'],
  Helsinki: ['Helsingfors'], Turku: ['Åbo'], Aarhus: ['Århus'], Reykjavik: ['Reykjavík'], Seville: ['Sevilla', 'Sevilla'], Nice: ['Nizza'],
  'New York City': ['New York', 'NYC', 'Nieuw-York'], 'Mexico City': ['Mexico-Stad', 'Mexico'], Dubai: ['Dubaj'], Singapore: ['Singapur'],
  Barcelona: ['Barcelone'], Bucharest: ['Boekarest', 'Bukarest'], Budapest: [], Hamburg: [], Frankfurt: ['Frankfurt am Main'], Stockholm: [], Oslo: [],
  Lyon: ['Lyons'], Marseille: ['Marseilles'], Gdańsk: ['Gdansk', 'Danzig'], Kraków: ['Krakow', 'Krakau'], Tallinn: [], Riga: [], Vilnius: [],
};
// Busy airports that serve small towns, mostly in the Nordics, Benelux and the UK.
const KEEP = new Set(['BLL', 'GOT', 'TOS', 'BOO', 'AES', 'EVE', 'KRS', 'HAU', 'MOL', 'KSU', 'ALF', 'KKN', 'LYR', 'AAL', 'FAE', 'KEF', 'LUX', 'MST', 'GRQ', 'OST', 'CRL', 'LGG', 'NYO', 'VST', 'LPI', 'NRK', 'VBY', 'RNB', 'KRN', 'LLA', 'UME', 'OSD', 'SDL', 'RVN', 'KTT', 'IVL', 'OUL', 'VAA', 'TMP', 'JYV', 'KUO', 'RNN', 'SGD', 'EBJ', 'STN', 'LTN', 'LGW', 'BHX', 'MAN', 'EDI', 'GLA', 'BRS', 'NCL', 'LBA', 'ABZ', 'BFS', 'DUB', 'SNN', 'ORK', 'EMA', 'BOH', 'SOU', 'EXT', 'INV', 'JER', 'GCI', 'IOM', 'DUS', 'NCE', 'BGY', 'CIA', 'BVA', 'HHN', 'NYO', 'WMI', 'SXF', 'BER']);
// Airports: only those serving a town of 30,000+, which drops thousands of small airstrips.
const towns = new Set();
for (const c of cities.filter((x) => x.population >= 30000)) {
  const n = norm(c.name);
  towns.add(n);
  const words = n.split(' ');
  if (words.length > 2) towns.add(words.slice(0, 2).join(' ')); // "new york city" also matches "new york"
}
for (const [canonical, list] of Object.entries(ALIASES)) for (const n of [canonical, ...list]) towns.add(norm(n));
for (const a of airports) {
  if (!a.iata || a.iata.length !== 3 || a.type !== 'airport' || !a.city || (!towns.has(norm(a.city)) && !KEEP.has(a.iata))) continue;
  iata[a.iata] = [a.city, round(a.latitude), round(a.longitude)];
  put(a.city, a.city, a.latitude, a.longitude, 1000); // small cities with airports; real cities win on population
}
for (const [canonical, list] of Object.entries(ALIASES)) {
  const hit = [canonical, ...list].map((n) => byName.get(norm(n))).find(Boolean);
  if (!hit) { console.warn(`no city for alias target ${canonical}`); continue; }
  byName.set(norm(canonical), [canonical, hit[1], hit[2], Number.MAX_SAFE_INTEGER]);
  for (const a of list) byName.set(norm(a), [hit[0], hit[1], hit[2], Number.MAX_SAFE_INTEGER]);
}
// Drop names that are also everyday words, so "Hold" or "Lunch" never become places.
for (const w of ['home', 'hold', 'focus', 'office', 'lunch', 'school', 'gym', 'sync', 'review', 'march', 'may', 'nice to', 'orange', 'reading', 'bath', 'mobile', 'split', 'eugene', 'victoria', 'florence', 'regina', 'young', 'university', 'brest', 'derby', 'luton']) if (!Object.values(ALIASES).flat().includes(w)) byName.delete(w);
// Airports newer than the OpenFlights snapshot.
const EXTRA_AIRPORTS = { BER: ['Berlin', 52.37, 13.5] };
for (const [code, v] of Object.entries(EXTRA_AIRPORTS)) iata[code] = v;
const placeRows = [...byName.entries()].map(([k, v]) => `${k}|${v[0] === k ? '' : v[0]}|${v[1]}|${v[2]}`).join(';');
const iataRows = Object.entries(iata).map(([code, v]) => `${code}${v[1]},${v[2]},${v[0]}`).join(';');
writeFileSync(join(root, 'js/geo/places.js'), `// Generated by tools/make-geo.mjs. Cities: GeoNames via all-the-cities (CC BY 4.0). Airports: OpenFlights (ODbL).\n// places: "normalised name|display name (empty if same)|lat|lon" rows. airports: "IATA lat,lon,city" rows.\nexport const PLACES = ${JSON.stringify(placeRows)};\nexport const AIRPORTS = ${JSON.stringify(iataRows)};\n`);
writeFileSync(join(root, 'js/geo/LICENSES.md'), `# Geo data\n\n- **land-dots.js**: derived from Natural Earth 1:110m land via world-atlas (public domain).\n- **places.js** city names and coordinates: GeoNames (https://www.geonames.org), licensed CC BY 4.0, via the all-the-cities package.\n- **places.js** airport codes and coordinates: OpenFlights (https://openflights.org/data), licensed under the Open Database License (ODbL) 1.0. This file is a derived database and is available under the same licence.\n\nRegenerate with \`node tools/make-geo.mjs\`.\n`);
console.log(`land dots: ${dots.length / 2}, places: ${byName.size}, airports: ${Object.keys(iata).length}`);
